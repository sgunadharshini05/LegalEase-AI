import io
import os
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from utils.document_formatter import sanitize_text

def generate_docx_file(doc_type: str, text_content: str, terms_list: list) -> bytes:
    doc = Document()

    # Header with Logo if available
    header = doc.sections[0].header
    hp = header.paragraphs[0]
    hp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    
    logo_path = os.path.join("assets", "logo.png")
    if os.path.exists(logo_path):
        try:
            hrun_img = hp.add_run()
            hrun_img.add_picture(logo_path, width=Inches(0.8))
        except Exception:
            pass

    hrun = hp.add_run("  LEGALEASE AI PLATFORM | CONFIDENTIAL")
    hrun.font.name = 'Calibri'
    hrun.font.size = Pt(8.5)
    hrun.font.color.rgb = RGBColor(128, 128, 128)

    # Title
    title_p = doc.add_paragraph()
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_run = title_p.add_run(sanitize_text(doc_type.upper()))
    title_run.bold = True
    title_run.font.name = 'Calibri'
    title_run.font.size = Pt(18)
    title_run.font.color.rgb = RGBColor(27, 54, 93)

    doc.add_paragraph()

    # Content Body
    clean_text = sanitize_text(text_content)
    for line in clean_text.split('\n'):
        if line.strip():
            p = doc.add_paragraph()
            p.paragraph_format.line_spacing = 1.15
            p.paragraph_format.space_after = Pt(4)
            run = p.add_run(line)
            run.font.name = 'Calibri'
            run.font.size = Pt(11)

    # Summary of Terms
    if terms_list:
        doc.add_paragraph()
        st_p = doc.add_paragraph()
        st_run = st_p.add_run("SUMMARY OF KEY TERMS & CONDITIONS:")
        st_run.bold = True
        st_run.font.name = 'Calibri'
        st_run.font.size = Pt(12)
        st_run.font.color.rgb = RGBColor(27, 54, 93)

        for term in terms_list:
            if term.strip():
                tp = doc.add_paragraph(style='List Bullet')
                tp.paragraph_format.space_after = Pt(2)
                trun = tp.add_run(sanitize_text(term.strip()))
                trun.font.name = 'Calibri'
                trun.font.size = Pt(10.5)

    # Footer
    footer = doc.sections[0].footer
    fp = footer.paragraphs[0]
    fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    frun = fp.add_run("Generated by LegalEase AI Platform - Legally Binding Draft")
    frun.font.name = 'Calibri'
    frun.font.size = Pt(8)
    frun.font.color.rgb = RGBColor(128, 128, 128)

    # Save Stream
    docx_stream = io.BytesIO()
    doc.save(docx_stream)
    docx_stream.seek(0)
    return docx_stream.getvalue()