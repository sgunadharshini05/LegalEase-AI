import os
from fpdf import FPDF
from utils.document_formatter import sanitize_text

class LegalPDF(FPDF):
    def header(self):
        logo_path = os.path.join("assets", "logo.png")
        if os.path.exists(logo_path):
            try:
                self.image(logo_path, 10, 8, 16)
                self.set_x(30)
            except Exception:
                pass
        
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(27, 54, 93)
        self.cell(0, 10, "LEGALEASE AI PLATFORM", new_x="RIGHT", new_y="TOP")
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, "CONFIDENTIAL & LEGALLY BINDING", new_x="LMARGIN", new_y="NEXT", align="R")
        self.line(10, 24, 200, 24)
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by LegalEase AI Platform", align="C")

def generate_pdf_file(doc_type: str, text_content: str, terms_list: list) -> bytes:
    pdf = LegalPDF()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=20)

    # Document Title
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(27, 54, 93)
    clean_title = sanitize_text(doc_type.upper())
    pdf.cell(0, 10, clean_title, new_x="LMARGIN", new_y="NEXT", align="C")
    pdf.ln(4)

    # Body Content
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(40, 40, 40)
    
    clean_text = sanitize_text(text_content)
    for line in clean_text.split('\n'):
        if line.strip():
            pdf.multi_cell(0, 6, line.strip())
            pdf.ln(2)

    # Summary Terms
    if terms_list:
        pdf.ln(4)
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(27, 54, 93)
        pdf.cell(0, 8, "SUMMARY OF KEY TERMS & CONDITIONS:", new_x="LMARGIN", new_y="NEXT")
        
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(40, 40, 40)
        for idx, term in enumerate(terms_list, 1):
            if term.strip():
                pdf.cell(5)
                pdf.cell(0, 6, f"{idx}. {sanitize_text(term.strip())}", new_x="LMARGIN", new_y="NEXT")

    # ✍️ Signature Section (Forced Page Check)
    if pdf.get_y() > 220:
        pdf.add_page()

    pdf.ln(10)
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(27, 54, 93)
    pdf.cell(0, 8, "IN WITNESS WHEREOF, the parties hereto have executed this Agreement:", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(6)

    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(0, 0, 0)
    
    # Party A & Party B Signature Columns
    pdf.cell(90, 6, "_____________________________________", new_x="RIGHT", new_y="TOP")
    pdf.cell(90, 6, "_____________________________________", new_x="LMARGIN", new_y="NEXT")
    
    pdf.cell(90, 6, "Authorized Signature (Party A)", new_x="RIGHT", new_y="TOP")
    pdf.cell(90, 6, "Authorized Signature (Party B)", new_x="LMARGIN", new_y="NEXT")
    
    pdf.cell(90, 6, "Date: ________________________", new_x="RIGHT", new_y="TOP")
    pdf.cell(90, 6, "Date: ________________________", new_x="LMARGIN", new_y="NEXT")

    return bytes(pdf.output())